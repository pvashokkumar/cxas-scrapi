"""PLACEHOLDERS.md of passport layout v4 (the human guide at the bundle root).

Order: what could not be read (resources, parts of resources such as a table
schema or the MCP server config, project reads; first, so nobody misses
them), the attached Google Cloud resources, identities and roles, every
placeholder with file and line, names kept from the source, the push command,
the tree.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING, Any

from cxas_scrapi.utils.passport import ids
from cxas_scrapi.utils.passport.graph import NOT_READABLE
from cxas_scrapi.utils.passport.manifest import WHOLE_RESOURCE, placeholder_help
from cxas_scrapi.utils.passport.model import PASSPORT_DIR_NAME
from cxas_scrapi.utils.passport.plugins.base import STATUS_TEXT
from cxas_scrapi.utils.passport.render import md_cell, md_code

if TYPE_CHECKING:
    from cxas_scrapi.utils.passport.graph import ResourceGraph


def _reference_patterns(kind: str, name: str) -> list[re.Pattern[str]]:
    """Where a file refers to the resource itself (not the same word in prose)."""
    n, end = re.escape(name), r"(?![A-Za-z0-9_-])"
    if kind == ids.BQ:
        return [
            re.compile(rf"[.:`]{n}(?=[.`\"'\\])"),
            re.compile(rf"(?<![A-Za-z0-9_-]){n}\.[A-Za-z_]"),
            re.compile(rf"(?m)^\s*-\s*{n}\s*$"),
            re.compile(rf"\"dataset\":\s*\"{n}\""),
        ]
    if kind == ids.RUN:
        return [
            re.compile(
                rf"//{n}-(?:\$\{{GCP_PROJECT_NUMBER\}}|\d+)\.[a-z0-9-]+\.run\.app"
            ),
            re.compile(rf"//{n}-[a-z0-9]+-[a-z]{{2,4}}\.a\.run\.app"),
            re.compile(rf"services/{n}{end}"),
        ]
    if kind == ids.SECRET:
        return [
            re.compile(rf"secrets/{n}{end}"),
            re.compile(rf"secretName:\s*['\"]?{n}{end}"),
            re.compile(
                rf"secretKeyRef:(?:\s+[A-Za-z]+:\s*\S+)*?\s+name:\s*['\"]?{n}{end}"
            ),
            re.compile(rf"\"secret\":\s*\"{n}\""),
        ]
    if kind == ids.SERVICE_ACCOUNT:
        return [re.compile(rf"(?<![A-Za-z0-9_-]){n}@")]
    if kind == ids.DATA_STORE:
        return [re.compile(rf"dataStores/{n}{end}")]
    if kind == ids.ENGINE:
        return [re.compile(rf"engines/{n}{end}")]
    if kind == ids.FUNCTION:
        return [
            re.compile(rf"cloudfunctions\.net/{n}{end}"),
            re.compile(rf"functions/{n}{end}"),
        ]
    return [re.compile(rf"/{n}{end}")]


def kept_names(
    graph: ResourceGraph, texts: dict[str, str], project_values: tuple[str, ...]
) -> list[tuple[str, str, list[str]]]:
    """(resource label, name, files that refer to it) for source-project names that stay.

    `texts`: agent files and passport config files (rel path -> text); a
    resource's own folder is not counted.
    """
    out = []
    for node in graph.ordered():
        if not graph.ctx.is_source(node.project) or any(
            v and v in node.name for v in project_values
        ):
            continue
        name = node.name.split("@", 1)[0]
        patterns = _reference_patterns(node.kind, name)
        own = f"{PASSPORT_DIR_NAME}/{node.folder}/"
        files = sorted(
            rel
            for rel, text in texts.items()
            if not rel.startswith(own) and any(p.search(text) for p in patterns)
        )
        out.append((graph.plugin_for(node).label_of(node), name, files))
    return out


def render_guide(
    *,
    app_display_name: str,
    graph: ResourceGraph,
    identities: list[dict[str, Any]],
    occurrences: dict[str, list[tuple[str, int, str]]],
    redactions: dict[str, list[tuple[str, int, str]]],
    portability: list[dict[str, Any]],
    kept: list[tuple[str, str, list[str]]],
    push_command: str,
    tree: list[tuple[str, str]],
    warnings: list[str],
    live: bool,
) -> str:
    lines = [
        f'# Passport of the CES agent "{app_display_name}"',
        "",
        "Generated by `cxas pull --passport` (bundle layout v4). The agent files are the files of a plain",
        "`cxas pull`, at the same paths; only values specific to the source project became placeholders.",
    ]
    if graph.nodes:
        lines += [
            "`passport/` captures every Google Cloud resource the agent uses, found by walking from its toolsets,",
            "tools and app settings through each service's own read-only API: BigQuery DDL (`schema.sql`) and",
            "prototype seed rows (`seed.sql`), Cloud Run and MCP specs (`service.yaml`, `tools.yaml`), Cloud",
            "Function source (`function.json`, `main.py`, `requirements.txt`), knowledge-base files, and Vertex AI",
            "Search data store config (`data_store.json`). Secret values and conversation recordings are never exported.",
            "",
        ]
    else:
        lines += [""]
    blocked = [n for n in graph.ordered() if n.status == NOT_READABLE]
    failures = list(graph.ctx.failures)
    if blocked or failures:
        lines += [
            f"## Not readable ({len(blocked) + len(failures)})",
            "",
            "The pull went on without these (exit 0); `cxas pull --passport --strict` fails instead.",
            "",
            "| Resource | What could not be read | Error | Missing |",
            "|---|---|---|---|",
        ]
        lines += [
            f"| {md_code(n.ref.id)} ({n.kind}) | {WHOLE_RESOURCE} | {md_cell(n.error or '')} | {md_cell(n.missing_permission or '')} |"
            for n in blocked
        ]
        lines += [
            f"| {md_code(f.id)} ({f.kind}) | {md_cell(f.what + (f' ({f.impact})' if f.impact else ''))} | {md_cell(f.error)} | {md_cell(f.missing_permission or '')} |"
            for f in failures
        ]
        lines.append("")
    if warnings:
        lines += (
            ["## Warnings", ""] + [f"- {md_cell(w)}" for w in warnings] + [""]
        )
    lines += [f"## Attached Google Cloud resources ({len(graph.nodes)})", ""]
    if not graph.nodes:
        lines += ["The agent uses no Google Cloud resource outside CES.", ""]
    else:
        lines += [
            "| Resource | Status | Why the agent uses it | Folder |",
            "|---|---|---|---|",
        ]
        for node in graph.ordered():
            plugin = graph.plugin_for(node)
            why = "; ".join(ev.text for ev in node.evidence[:3]) + (
                " ..." if len(node.evidence) > 3 else ""
            )
            has_dir = (
                bool(plugin.files(node, graph.ctx))
                or node.status != "read"
                or bool(graph.failures_of(node.ref))
            )
            folder_cell = (
                f"`{PASSPORT_DIR_NAME}/{node.folder}/`"
                if has_dir
                else f"`{PASSPORT_DIR_NAME}/manifest.json`"
            )
            lines.append(
                f"| {plugin.label_of(node)} | {STATUS_TEXT.get(node.status, node.status)} | {md_cell(why)} | {folder_cell} |"
            )
        lines.append("")
    if identities:
        lines += [
            "## Identities and roles",
            "",
            "| Identity | Project roles | Roles on attached resources |",
            "|---|---|---|",
        ]
        for ident in identities:
            project_roles = ident["project_roles"]
            roles = (
                ", ".join(md_code(r) for r in project_roles)
                if project_roles
                else ("not read" if project_roles is None else "none")
            )
            on_res = (
                ", ".join(
                    f"{md_code(r['role'])} on `{r['resource'].rsplit('/', 1)[-1]}`"
                    for r in ident["roles_on_attached_resources"]
                )
                or "none"
            )
            lines.append(
                f"| {md_code(ident['member'])} ({md_cell(ident['identity'])}) | {roles} | {on_res} |"
            )
        lines.append("")
    lines += _placeholders(occurrences)
    if redactions:
        lines += [
            "## Redacted credentials",
            "",
            "Credential-like values in the live configs are not in the bundle. They appear only in `passport/` files;",
            "the push does not need them.",
            "",
            "| Placeholder | Where |",
            "|---|---|",
        ]
        lines += [
            f"| `${{{name}}}` | "
            + "<br>".join(f"`{f}`:{n}" for f, n, _ in occ)
            + " |"
            for name, occ in sorted(redactions.items())
        ]
        lines.append("")
    if portability:
        lines += ["## Values changed for portability", ""]
        lines += [
            f"- `{p['file']}` line {p['line']}: {p['change']}"
            for p in portability
        ] + [""]
    if kept:
        lines += [
            "## Names kept from the source",
            "",
            "Resource names are not placeholders: the target project needs resources with the same names, or you",
            "change them in the files that refer to them.",
            "",
            "| Resource | Name | Files that refer to it |",
            "|---|---|---|",
        ]
        lines += [
            f"| {label} | {md_code(name)} | {', '.join(md_code(f) for f in files) or 'none'} |"
            for label, name, files in kept
        ]
        lines.append("")
    lines += _setup_steps(graph, identities)
    lines += ["## Push", "", "```bash", push_command, "```", ""]
    if not live:
        lines += [
            "> The pull ran without live reads (--no-live-introspect): resource folders hold READMEs only.",
            "",
        ]
    lines += ["## Bundle", "", "```text"]
    lines += [f"{path:<60} {comment}".rstrip() for path, comment in tree]
    lines += ["```", ""]
    return "\n".join(lines)


def _placeholders(
    occurrences: dict[str, list[tuple[str, int, str]]],
) -> list[str]:
    if not occurrences:
        return [
            "## Placeholders",
            "",
            "None: the agent files hold no value specific to the source project.",
            "",
        ]
    lines = [
        "## Placeholders",
        "",
        "| Placeholder | Replace with | How it is set | Where |",
        "|---|---|---|---|",
    ]
    for name, occ in sorted(occurrences.items()):
        replace_with, how = placeholder_help(name)
        where = "<br>".join(f"`{f}`:{n}" for f, n, _ in occ[:12]) + (
            f"<br>... {len(occ) - 12} more" if len(occ) > 12 else ""
        )
        lines.append(
            f"| `${{{name}}}` | {md_cell(replace_with)} | {md_cell(how)} | {where} |"
        )
    lines.append("")
    return lines


def _setup_steps(
    graph: ResourceGraph, identities: list[dict[str, Any]]
) -> list[str]:
    if not graph.nodes:
        return []
    apis = ["ces.googleapis.com", "cloudresourcemanager.googleapis.com"]
    api_map = {
        ids.BQ: ("bigquery.googleapis.com",),
        ids.RUN: ("run.googleapis.com",),
        ids.FUNCTION: (
            "cloudfunctions.googleapis.com",
            "run.googleapis.com",
            "cloudbuild.googleapis.com",
            "artifactregistry.googleapis.com",
        ),
        ids.SECRET: ("secretmanager.googleapis.com",),
        ids.BUCKET: ("storage.googleapis.com",),
        ids.DATA_STORE: ("discoveryengine.googleapis.com",),
        ids.ENGINE: ("discoveryengine.googleapis.com",),
        ids.SERVICE_ACCOUNT: ("iam.googleapis.com",),
    }
    for n in graph.ordered():
        for svc in api_map.get(n.kind, ()):
            if svc not in apis:
                apis.append(svc)
    id_cmds = [
        "`gcloud beta services identity create --service=ces.googleapis.com --project=<TARGET_PROJECT>`"
    ]
    if "discoveryengine.googleapis.com" in apis:
        id_cmds.append(
            "`gcloud beta services identity create --service=discoveryengine.googleapis.com --project=<TARGET_PROJECT>`"
        )
    steps = [
        f"Enable APIs (`gcloud services enable {' '.join(apis)} --project=<TARGET_PROJECT>`) and create service identities ({' and '.join(id_cmds)})."
    ]
    sas = [n.name.split("@", 1)[0] for n in graph.by_kind(ids.SERVICE_ACCOUNT)]
    if sas or identities:
        sa_part = (
            f"create service account(s) {', '.join(md_code(s) for s in sas)} (`gcloud iam service-accounts create <SA> --project=<TARGET_PROJECT>`) and "
            if sas
            else ""
        )
        steps.append(
            f"IAM & identities: {sa_part}grant the project roles and resource-level IAM bindings listed in **Identities and roles** above (`passport/manifest.json` -> `identities` and each resource's `iam.bindings`)."
        )
    if bqs := graph.by_kind(ids.BQ):
        items = ", ".join(
            f"`{n.name}` (`{PASSPORT_DIR_NAME}/{n.folder}/`)" for n in bqs
        )
        steps.append(
            f'BigQuery: create dataset(s) {items}, run `schema.sql` and `seed.sql` (substituting `${{GCP_PROJECT}}`), and grant dataset IAM roles (`GRANT \\`<ROLE>\\` ON SCHEMA \\`<TARGET_PROJECT>.<DATASET>\\` TO "serviceAccount:<SA>"`).'
        )
    if bkts := graph.by_kind(ids.BUCKET):
        items = ", ".join(
            f"`gs://{n.name}` (`{PASSPORT_DIR_NAME}/{n.folder}/files/`)"
            for n in bkts
        )
        steps.append(
            f"Cloud Storage: create bucket(s) {items}, upload `files/*` (substituting `${{GCP_PROJECT}}` in `.jsonl`/`.md` files), and grant `roles/storage.objectViewer` to every `serviceAccount:` in the bucket's `iam.bindings` (including `service-${{GCP_PROJECT_NUMBER}}@gcp-sa-discoveryengine.iam.gserviceaccount.com` when Vertex AI Search imports from the bucket)."
        )
    if secs := graph.by_kind(ids.SECRET):
        items = ", ".join(md_code(n.name) for n in secs)
        steps.append(
            f"Secret Manager: create secret(s) {items} (`--replication-policy=automatic`), add a version for each (for MCP Toolbox secrets, render `tools.yaml` from `{PASSPORT_DIR_NAME}/cloud_run/<service>/tools.yaml` with `${{GCP_PROJECT}}` replaced; for API key secrets, add a secret version), and grant `roles/secretmanager.secretAccessor` to the `serviceAccount:` principals in `iam.bindings`."
        )
    if dss := graph.by_kind(ids.DATA_STORE):
        items = ", ".join(
            f"`{n.name}` (location `{n.location or 'us'}`, endpoint `https://{(n.location or 'us') + '-' if (n.location or 'us') != 'global' else ''}discoveryengine.googleapis.com`, `{PASSPORT_DIR_NAME}/{n.folder}/data_store.json`)"
            for n in dss
        )
        steps.append(
            f'Vertex AI Search: create data store(s) {items} (`contentConfig: CONTENT_REQUIRED`, `solutionTypes: ["SOLUTION_TYPE_SEARCH"]`), patch `schemas/default_schema` from `data_store.json`, and import documents from `gs://<BUCKET>/search/policy_docs.jsonl` (`reconciliationMode: FULL` or `POST .../branches/0/documents?documentId=<id>`).'
        )
    if runs := graph.by_kind(ids.RUN):
        items = ", ".join(
            f"`{n.name}` (`{n.location}`, `{PASSPORT_DIR_NAME}/{n.folder}/service.yaml`)"
            for n in runs
        )
        steps.append(
            f"Cloud Run: deploy service(s) {items} (substitute `${{GCP_PROJECT}}` and `${{GCP_PROJECT_NUMBER}}`, preserve `run.googleapis.com/custom-audiences`), and grant `roles/run.invoker` to `service-${{GCP_PROJECT_NUMBER}}@gcp-sa-ces.iam.gserviceaccount.com`."
        )
    if fns := graph.by_kind(ids.FUNCTION):
        items = [
            f"`{n.name}` (`{n.location}`, `{PASSPORT_DIR_NAME}/{n.folder}/`"
            + (
                f" + `gcloud run services update {n.name} --region={n.location} --project=<TARGET_PROJECT> --no-invoker-iam-check`"
                if (n.config.get("serviceConfig") or {}).get(
                    "invokerIamDisabled"
                )
                else ""
            )
            + ")"
            for n in fns
        ]
        steps.append(
            f"Cloud Functions: deploy {', '.join(items)} from `main.py`, `requirements.txt`, and `function.json` (`--gen2 --trigger-http --no-allow-unauthenticated`)."
        )
    return (
        ["## Target project setup", ""]
        + [f"{i}. {s}" for i, s in enumerate(steps, 1)]
        + [""]
    )


def tree_rows(
    agent_rels: list[str], written: list[dict[str, str]]
) -> list[tuple[str, str]]:
    """(path, comment) rows: agent top-level entries, the guide, then passport/ folders."""
    rows: list[tuple[str, str]] = []
    top: dict[str, int] = {}
    for rel in agent_rels:
        first, _, rest = rel.partition("/")
        key = first + ("/" if rest else "")
        top[key] = top.get(key, 0) + 1
    for key in sorted(top, key=lambda k: (k.endswith("/"), k.lower())):
        rows.append(
            (
                key,
                f"{top[key]} file(s): same as a plain pull"
                if key.endswith("/")
                else "",
            )
        )
    rows.append(("PLACEHOLDERS.md", "this guide"))
    rows.append((f"{PASSPORT_DIR_NAME}/", ""))
    rows.append(
        (
            f"{PASSPORT_DIR_NAME}/manifest.json",
            "machine-readable index of everything below",
        )
    )
    folders: dict[str, list[str]] = {}
    for item in written:
        parts = item["path"].split("/")
        if len(parts) >= 4:
            folders.setdefault("/".join(parts[:3]) + "/", []).append(
                "/".join(parts[3:])
            )
    current_service = ""
    for folder in sorted(folders):
        service = folder.split("/")[1]
        if service != current_service:
            rows.append((f"{PASSPORT_DIR_NAME}/{service}/", ""))
            current_service = service
        rows.append((folder, ", ".join(sorted(folders[folder]))))
    return rows
